export function postcard(id, caption = '') {
  const sc = SCENES[id];
  if (!sc) return '';
  const [top, bottom] = SKY[sc.sky];
  const g = `sky-${id}`;
  return `<svg class="postcard" viewBox="0 0 48 32" shape-rendering="crispEdges" role="img" aria-label="${caption || id}">
    <defs><linearGradient id="${g}" x1="0" y1="0" x2="0" y2="1"><stop offset="0" stop-color="${top}"/><stop offset="1" stop-color="${bottom}"/></linearGradient></defs>
    <rect width="48" height="32" fill="url(#${g})"/>
    ${sc.blocks.map(([c, x, y, w, h]) => `<rect x="${x}" y="${y}" width="${w}" height="${h}" fill="${c}"/>`).join('')}
  </svg>`;
}
